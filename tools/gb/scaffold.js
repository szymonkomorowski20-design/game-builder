function gitattributes(lfs) {
  let s = '# Normalize line endings (Godot files use LF)\n* text=auto eol=lf\n\n# Binary assets\n';
  const bin = ['png', 'jpg', 'jpeg', 'webp', 'svgz', 'wav', 'ogg', 'mp3', 'glb', 'fbx', 'blend', 'obj', 'ttf', 'otf', 'exr', 'hdr', 'psd', 'aseprite', 'zip'];
  for (const e of bin) s += lfs ? `*.${e} filter=lfs diff=lfs merge=lfs -text\n` : `*.${e} binary\n`;
  return s;
}

