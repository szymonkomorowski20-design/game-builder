function fill(tpl, o) {
  return tpl
    .replace(/\{\{NAME\}\}/g, o.name)
    .replace(/\{\{VERSION\}\}/g, pluginVersion())
    .replace(/\{\{ENGINE\}\}/g, o.engine)
    .replace(/\{\{DIM\}\}/g, dimLabel(o))
    .replace(/\{\{RENDERER\}\}/g, `${RENDERERS[o.renderer]} (\`${o.renderer}\`)`)
    .replace(/\{\{WIDTH\}\}/g, String(o.width))
    .replace(/\{\{HEIGHT\}\}/g, String(o.height))
    .replace(/\{\{PIXEL_NOTE\}\}/g, o.pixelArt ? ' · pixel art (viewport stretch, nearest filter, pixel snap)' : '')
    .replace(/\{\{TESTS\}\}/g, o.tests === 'none' ? 'none yet (decided later; `gb test` reports SKIP)' : `${o.tests} (installed into addons/ — until then \`gb test\` reports SKIP)`);
}

function plan(o) {
  const files = [];
  const add = (rel, content, mode) => files.push({ rel, content, mode });
  const copy = (rel, src) => files.push({ rel, src });
  const copyTree = (relDir, srcDir) => {
    for (const e of fs.readdirSync(srcDir, { withFileTypes: true })) {
      if (e.isDirectory()) copyTree(`${relDir}/${e.name}`, path.join(srcDir, e.name));
      else copy(`${relDir}/${e.name}`, path.join(srcDir, e.name));
    }
  };

  add('project.godot', projectGodot(o));
  if (o.templateInfo) {
    // A starter game replaces the placeholder main scene; its own files (scenes, scripts, data,
    // tests, its implemented spec) are copied as-is.
    const tdir = path.join(TPL, 'games', o.template);
    for (const e of fs.readdirSync(tdir, { withFileTypes: true })) {
      if (e.name === 'template.json') continue;
      if (e.isDirectory()) copyTree(e.name, path.join(tdir, e.name));
      else copy(e.name, path.join(tdir, e.name));
    }
  } else {
    add('scenes/main.tscn', mainScene(o));
    copy('scripts/main.gd', path.join(TPL, 'project', 'scripts', 'main.gd'));
  }
  copy('autoload/events.gd', path.join(TPL, 'project', 'autoload', 'events.gd'));
  add('assets/.gitkeep', '');
  add('data/.gitkeep', '');
  add('tests/README.md', TESTS_README);
  copy('tests/scenarios/smoke.gd', path.join(TPL, 'project', 'tests', 'scenarios', 'smoke.gd'));
  add('tests/replays/.gitkeep', '');
  add('tests/baselines/.gdignore', ''); // baselines are gb data, never imported or exported by Godot
  if (o.tests === 'gut') {
    const example = path.join(TPL, 'project', 'tests', 'unit', 'test_example.gd');
    // Adoption never adds an Events autoload, so the example must not assert one the project does not have.
    if (o.adopt && !o.hasEvents) add('tests/unit/test_example.gd', fs.readFileSync(example, 'utf8').replace(/\r\n/g, '\n').replace(/func test_events_autoload_exists\(\)[^\n]*\n[^\n]*\n\n\n/, ''));
    else copy('tests/unit/test_example.gd', example);
  }
  copyTree('addons/gb_harness', path.join(TPL, 'addons', 'gb_harness'));
  if (o.tests === 'gut') copyTree('addons/gut', path.join(PLUGIN, 'vendor', 'gut', 'addons', 'gut'));
  add('export_presets.cfg', exportPresets());
  add('.ai/perf-budget.json', PERF_BUDGET);
  add('.github/workflows/verify.yml', fs.readFileSync(path.join(TPL, 'repo', 'ci-verify.yml'), 'utf8').replace('{{GODOT_FULL}}', o.engineFull || o.engine));
  add('.gitignore', GITIGNORE);
  add('.gitattributes', gitattributes(o.lfs));
  add('.editorconfig', EDITORCONFIG);

  for (const f of ['gb.js', 'lint.js', 'credits.js', 'check_all.gd', 'setup_input.gd', 'project_setting.gd', 'imgdiff.gd']) copy(`tools/gb/${f}`, path.join(__dirname, f));
  add('tools/gb/.gdignore', '');
  add('tools/gb/ignore-errors.txt', IGNORE_ERRORS);

  add('AGENTS.md', fill(fs.readFileSync(path.join(TPL, 'repo', 'AGENTS.md.tmpl'), 'utf8'), o));
  add('CLAUDE.md', '@AGENTS.md\n');
  add('README.md', readme(o));
  add('STATUS.md', `# Status — ${o.name}\n\nPostęp gry wg specyfikacji (aktualizowany na każdej bramce fazy).\n\n| Spec | Faza | Stan | Grywalne? | Werdykt gracza |\n|---|---|---|---|---|\n`);

  const aiFiles = JSON.parse(fs.readFileSync(path.join(TPL, 'ai', 'files.json'), 'utf8'));
  for (const [rel, content] of Object.entries(aiFiles)) if (!rel.startsWith('_')) add(`.ai/${rel}`, content);
  for (const c of fs.readdirSync(path.join(TPL, 'ai', 'checklists'))) copy(`.ai/checklists/${c}`, path.join(TPL, 'ai', 'checklists', c));
  copy('.ai/skills/spec-writing/SKILL.md', path.join(TPL, 'ai', 'skills', 'spec-writing', 'SKILL.md'));
  add('.ai/adr/ADR-001-engine-and-setup.md', adr001(o));

  copy('.claude/settings.json', path.join(TPL, 'claude', 'settings.json'));
  copy('.claude/hooks/session-start.sh', path.join(TPL, 'claude', 'hooks', 'session-start.sh'));
  copy('.claude/hooks/guard-protected-paths.sh', path.join(TPL, 'claude', 'hooks', 'guard-protected-paths.sh'));
  copy('.claude/hooks/check-on-edit.sh', path.join(TPL, 'claude', 'hooks', 'check-on-edit.sh'));
  return files;
}

/**
 * In adopt mode the game's own files are never generated — only the methodology layer + tools.
 * Even then nothing existing is overwritten (the general rule), but skipping these keeps the
 * report honest: an adopted project does not get a placeholder main scene "KEPT" next to its own.
 */
const GAME_FILES = new Set(['project.godot', 'scenes/main.tscn', 'scripts/main.gd', 'autoload/events.gd', 'assets/.gitkeep', 'data/.gitkeep', 'export_presets.cfg']);
// Adopt installs these through `gb harness install` / `gb tests install`, which also register
// them with the engine (autoload, editor plugin) instead of copying files the project never loads.
const GAME_DIRS = ['addons/gb_harness/', 'addons/gut/'];

function scaffold(o, { runGodot = null, dryRun = false } = {}) {
  const report = [];
  for (const f of plan(o)) {
    if (o.adopt && (GAME_FILES.has(f.rel) || GAME_DIRS.some((d) => f.rel.startsWith(d)))) continue;
    const dst = path.join(o.dir, f.rel);
    if (fs.existsSync(dst)) { report.push(`KEPT    ${f.rel}`); continue; }
    report.push(`CREATED ${f.rel}`);
    if (dryRun) continue;
    fs.mkdirSync(path.dirname(dst), { recursive: true });
    if (f.src) fs.copyFileSync(f.src, dst);
    else fs.writeFileSync(dst, f.content);
  }
  if (!dryRun && runGodot) {
    const r = runGodot(['--headless', '--path', o.dir, '--script', path.join(o.dir, 'tools', 'gb', 'setup_input.gd')]);
    const m = /GB_INPUT_DONE added=(\d+) err=(\d+)/.exec(r);
    report.push(m ? `INPUT   ${m[1]} default action(s) added via Godot (existing actions untouched)` : 'FAIL    input actions: setup_input.gd did not report — run it manually');
  }
  return report;
}

function parseScaffoldArgs(argv) {
  const o = { dir: process.cwd(), name: null, dim: '2d', renderer: null, pixelArt: false, width: null, height: null, tests: 'gut', lfs: false, engine: null, adopt: false, dryRun: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const v = () => argv[++i];
    if (a === '--dir') o.dir = path.resolve(v());
    else if (a === '--name') o.name = v();
    else if (a === '--dim') { o.dim = v().toLowerCase(); o.dimGiven = true; }
    else if (a === '--renderer') o.renderer = v();
    else if (a === '--pixel-art') o.pixelArt = true;
    else if (a === '--width') o.width = Number(v());
    else if (a === '--height') o.height = Number(v());
    else if (a === '--tests') o.tests = v();
    else if (a === '--lfs') o.lfs = true;
    else if (a === '--engine') o.engine = v();
    else if (a === '--adopt') o.adopt = true;
    else if (a === '--dry-run') o.dryRun = true;
    else if (a === '--template') o.template = v();
    else throw new Error(`scaffold: unknown option ${a}`);
  }
  if (o.template) {
    const f = path.join(TPL, 'games', o.template, 'template.json');
    if (!fs.existsSync(f)) throw new Error(`scaffold: unknown template "${o.template}" (have: ${listTemplates().join(', ') || 'none'})`);
    o.templateInfo = JSON.parse(fs.readFileSync(f, 'utf8'));
    o.dim = o.templateInfo.dim;
    if (!o.width && o.templateInfo.viewport) [o.width, o.height] = o.templateInfo.viewport;
  }
  if (!['2d', '3d'].includes(o.dim)) throw new Error('scaffold: --dim must be 2d or 3d');
  const existing = path.join(o.dir, 'project.godot');
  if (o.adopt && fs.existsSync(existing)) Object.assign(o, existingSettings(fs.readFileSync(existing, 'utf8')));
  o.renderer = o.renderer || (o.dim === '3d' ? 'forward_plus' : 'gl_compatibility');
  if (!RENDERERS[o.renderer]) throw new Error(`scaffold: --renderer must be one of ${Object.keys(RENDERERS).join(', ')}`);
  if (!['gut', 'gdunit4', 'none'].includes(o.tests)) throw new Error('scaffold: --tests must be gut, gdunit4 or none');
  o.width = o.width || (o.pixelArt ? 320 : 1280);
  o.height = o.height || (o.pixelArt ? 180 : 720);
  o.name = o.name || path.basename(o.dir);
  return o;
}

/**
 * Adopt mode documents the project as it IS: renderer, base resolution, pixel-art filter and the Events
 * autoload are read from its project.godot, with Godot's own defaults where a key is absent — never the
 * new-project defaults (an adopted game without a [rendering] section runs Forward+ at 1152×648).
 */
function existingSettings(text) {
  const get = (key) => {
    const m = new RegExp(`^${key.replace(/[/.]/g, '\\$&')}=(.+)$`, 'm').exec(text);
    return m ? m[1].trim().replace(/^"|"$/g, '') : null;
  };
  const renderer = get('renderer/rendering_method');
  return {
    renderer: renderer && RENDERERS[renderer] ? renderer : 'forward_plus',
    width: Number(get('window/size/viewport_width')) || 1152,
    height: Number(get('window/size/viewport_height')) || 648,
    pixelArt: get('textures/canvas_textures/default_texture_filter') === '0',
    hasEvents: /^Events=/m.test(text),
  };
}

function listTemplates() {
  try {
    return fs.readdirSync(path.join(TPL, 'games')).filter((d) => fs.existsSync(path.join(TPL, 'games', d, 'template.json')));
  } catch {
    return [];
  }
}

