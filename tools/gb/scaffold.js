'use strict';

/**
 * gb scaffold — generate a new game-builder Godot project (game-bootstrap Case B), or add the
 * missing methodology pieces to an existing one (Case C, --adopt).
 *
 * IDEMPOTENT by construction: an existing file is never overwritten — it is reported as KEPT.
 * That is what makes Case C safe (adopting a running project must not touch its code) and what
 * makes a re-run after a partial failure harmless.
 *
 * Runs from the PLUGIN copy only (it needs ../../templates). The copy of tools/gb placed into the
 * game repo does not carry this file.
 */

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const PLUGIN = path.resolve(__dirname, '..', '..');
const TPL = path.join(PLUGIN, 'templates');

const RENDERERS = {
  forward_plus: 'Forward Plus',
  mobile: 'Mobile',
  gl_compatibility: 'GL Compatibility',
};

function pluginVersion() {
  try {
    return fs.readFileSync(path.join(PLUGIN, 'VERSION'), 'utf8').trim();
  } catch {
    return '0.0.0';
  }
}

function projectGodot(o) {
  const pixel = o.pixelArt;
  const lines = [
    '; Engine configuration file. Generated by game-builder scaffold; edit through the Godot editor.',
    '',
    'config_version=5',
    '',
    '[application]',
    '',
    `config/name="${o.name.replace(/"/g, '\\"')}"`,
    `run/main_scene="${o.templateInfo ? o.templateInfo.main_scene : 'res://scenes/main.tscn'}"`,
    `config/features=PackedStringArray("${o.engine}", "${RENDERERS[o.renderer]}")`,
    '',
    '[autoload]',
    '',
    'Events="*res://autoload/events.gd"',
    'GbHarness="*res://addons/gb_harness/harness.gd"',
    '',
    ...(o.tests === 'gut' ? ['[editor_plugins]', '', 'enabled=PackedStringArray("res://addons/gut/plugin.cfg")', ''] : []),
    '[display]',
    '',
    `window/size/viewport_width=${o.width}`,
    `window/size/viewport_height=${o.height}`,
    ...(o.templateInfo && o.templateInfo.window
      ? [`window/size/window_width_override=${o.templateInfo.window[0]}`, `window/size/window_height_override=${o.templateInfo.window[1]}`]
      : pixel && o.width * 4 <= 1920 ? [`window/size/window_width_override=${o.width * 4}`, `window/size/window_height_override=${o.height * 4}`] : []),
    `window/stretch/mode="${pixel ? 'viewport' : 'canvas_items'}"`,
    `window/stretch/aspect="${pixel ? 'keep' : 'expand'}"`,
    // integer scaling keeps pixels square and crisp (Godot 4.7 docs: display/window/stretch/scale_mode)
    ...(pixel ? ['window/stretch/scale_mode="integer"'] : []),
    '',
    '[rendering]',
    '',
    `renderer/rendering_method="${o.renderer}"`,
    `renderer/rendering_method.mobile="${o.renderer === 'forward_plus' ? 'mobile' : o.renderer}"`,
  ];
  if (pixel) lines.push('textures/canvas_textures/default_texture_filter=0', '2d/snap/snap_2d_transforms_to_pixel=true');
  return lines.join('\n') + '\n';
}

function mainScene(o) {
  const head = `[gd_scene format=3]\n\n[ext_resource type="Script" path="res://scripts/main.gd" id="1_main"]\n\n`;
  const label = o.name.replace(/"/g, '\\"');
  if (o.dim === '3d') {
    return head +
      `[node name="Main" type="Node3D"]\nscript = ExtResource("1_main")\n\n` +
      `[node name="Camera3D" type="Camera3D" parent="."]\ntransform = Transform3D(1, 0, 0, 0, 0.939693, 0.34202, 0, -0.34202, 0.939693, 0, 3, 6)\n\n` +
      `[node name="Sun" type="DirectionalLight3D" parent="."]\ntransform = Transform3D(1, 0, 0, 0, 0.707107, 0.707107, 0, -0.707107, 0.707107, 0, 5, 0)\n\n` +
      `[node name="Floor" type="CSGBox3D" parent="."]\ntransform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, -0.5, 0)\nuse_collision = true\nsize = Vector3(20, 1, 20)\n\n` +
      `[node name="Label" type="Label" parent="."]\noffset_left = 16.0\noffset_top = 16.0\ntext = "${label} — game-builder"\n`;
  }
  return head +
    `[node name="Main" type="Node2D"]\nscript = ExtResource("1_main")\n\n` +
    `[node name="Camera2D" type="Camera2D" parent="."]\nanchor_mode = 0\n\n` +
    `[node name="Label" type="Label" parent="."]\noffset_left = 16.0\noffset_top = 16.0\ntext = "${label} — game-builder"\n`;
}

